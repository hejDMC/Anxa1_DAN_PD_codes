# ------------------ FEATUREPLOT LOOP (CUSTOM GRADIENT + CAPPING @ 3) ------------------
# NOTE: Only capping for visualization (plotting); original expression remains untouched.
for (gene in genes_found) {
  expr_data <- FetchData(da_seurat, vars = c(gene, "umap_1", "umap_2"))
  colnames(expr_data) <- c("expression", "Dim1", "Dim2")
  expr_data$expression_capped <- pmin(expr_data$expression, 3)  # <-- cap at 3 for the color scale
  expr_data$highlight <- expr_data$expression > 0               # keep original >0 for highlight
  
  p <- ggplot(expr_data, aes(x = Dim1, y = Dim2)) +
    geom_point(aes(color = expression_capped), size = 1) +
    geom_point(data = subset(expr_data, highlight), aes(x = Dim1, y = Dim2), color = NA, size = 1) +
    scale_color_gradientn(colors = c("lightgray", "#B34B50", "#5F070C", "#240705"), limits = c(0, 3)) +
    ggtitle(paste("Expression of", gene)) +
    theme_void() +
    theme(plot.title = element_text(hjust = 0.5), legend.position = "none")
  
  # Save PNG + PDF
  ggsave(file.path(output_dir, paste0("featureplot_", gene, ".png")), p, device = "png", width = 5, height = 5, dpi = 600)
  ggsave(file.path(output_dir, paste0("featureplot_", gene, ".pdf")), p, device = "pdf", width = 5, height = 5)
}

