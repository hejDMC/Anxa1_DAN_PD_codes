ks.test(da_seurat$MitoparkScore1, "pnorm",
        mean = mean(da_seurat$MitoparkScore1),
        sd = sd(da_seurat$MitoparkScore1))

mitopark_thr <- median(da_seurat$MitoparkScore1) + 2*mad(da_seurat$MitoparkScore1)     
da_seurat$MitoparkHigh <- da_seurat$MitoparkScore1 > mitopark_thr
da_seurat$mitopark_group <- ifelse(da_seurat$MitoparkHigh, "High", "Low")

