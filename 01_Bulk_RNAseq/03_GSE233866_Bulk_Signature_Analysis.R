p1 <- ggplot(dens_df, aes(x = x, y = y)) +
  geom_area(aes(fill = group), alpha = 0.6) +
  geom_vline(xintercept = mitopark_thr, linetype = "dashed", color = "#0080C0") +
  scale_fill_manual(values = c("Low" = "grey70", "High" = "#0080C0")) +
  labs(title = "Density of Mitopark Score", x = "MitoparkScore1", y = "Density") +
  theme_minimal() +
  theme(legend.position = "none")

