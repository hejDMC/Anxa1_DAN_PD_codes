# ---- BEHAVIOR EPISODES FROM Z-SCORES ----
# Finds contiguous episodes where z-score > +thr or < -thr for each behavioral variable.
# Returns one row per episode with start/end/peak info and an event time (peak or start).
get_behavior_episodes <- function(df,
                                  time_col       = "time",
                                  vars           = NULL,           # if NULL -> auto-detect behavioral vars
                                  z_thr          = 1.96,
                                  min_interval   = 5,              # seconds between episode anchors
                                  frame.behavior = frame.behavior,
                                  event_anchor   = c("peak","start")) {
  event_anchor <- match.arg(event_anchor)
  
  # choose variables (numeric, exclude coordinates/probs/signals/time/motif & binary in_center)
  if (is.null(vars)) {
    num_cols <- names(df)[sapply(df, is.numeric)]
    drop_pat <- "(?:_(x|y|prob)$)|^(time|motif|in_center|signal$|signalLeft|signalRight|signalLR_.*)$"
    vars <- setdiff(num_cols, grep(drop_pat, num_cols, value = TRUE))
  }
  
  out <- lapply(vars, function(v) {
    x <- df[[v]]
    if (all(is.na(x))) return(NULL)
    
    # z-score (mean/sd) across the entire recording
    z <- as.numeric(scale(x))
    flag <- ifelse(z > z_thr,  1L,
                   ifelse(z < -z_thr, -1L, 0L))  # 1 = high episode, -1 = low, 0 = none
    flag[is.na(flag)] <- 0L
    
    nz_idx <- which(flag != 0L)
    if (length(nz_idx) == 0) return(NULL)
    
    # group contiguous indices into episodes
    grp    <- c(1L, 1L + cumsum(diff(nz_idx) > 1L))
    starts <- tapply(nz_idx, grp, min) |> as.integer()
    ends   <- tapply(nz_idx, grp, max) |> as.integer()
    
    # peak within each episode (by |z|)
    peak_idx <- mapply(function(s, e) s - 1 + which.max(abs(z[s:e])), starts, ends)
    peak_z   <- z[peak_idx]
    etype    <- ifelse(flag[starts] == 1L, "high", "low")
    
    start_time <- df[[time_col]][starts]
    end_time   <- df[[time_col]][ends]
    peak_time  <- df[[time_col]][peak_idx]
    duration_s <- (ends - starts + 1) * frame.behavior
    
    # choose anchor: peak or episode onset
    anchor_time <- if (event_anchor == "peak") peak_time else start_time
    
    o <- order(anchor_time)
    starts     <- starts[o]; ends <- ends[o]; peak_idx <- peak_idx[o]
    peak_z     <- peak_z[o]; etype <- etype[o]
    start_time <- start_time[o]; end_time <- end_time[o]
    peak_time  <- peak_time[o]; duration_s <- duration_s[o]; anchor_time <- anchor_time[o]
    
    # enforce minimal spacing (min_interval) between episode anchors
    keep   <- logical(length(starts))
    last_t <- -Inf
    for (i in seq_along(starts)) {
      if ((anchor_time[i] - last_t) >= min_interval) {
        keep[i] <- TRUE
        last_t  <- anchor_time[i]
      }
    }
    
    tibble::tibble(
      event_time  = if (event_anchor == "peak") peak_time[keep] else start_time[keep],
      event_idx   = if (event_anchor == "peak") peak_idx[keep] else starts[keep],
      event_var   = v,
      event_type  = ifelse(etype[keep] == "high", "high", "low"),
      start_time  = start_time[keep],
      end_time    = end_time[keep],
      peak_time   = peak_time[keep],
      peak_z      = peak_z[keep],
      duration_s  = duration_s[keep]
    )
  })
  
  dplyr::bind_rows(out)
}

# ---- MOTIF ONSETS (from 'motif' column) ----
# Finds motif onset indices and enforces minimal spacing per motif.
get_motif_onsets <- function(df,
                             time_col       = "time",
                             motif_col      = "motif",
                             exclude_levels = 0,   # set to NULL to include all motifs
                             min_interval   = 5) {
  m <- df[[motif_col]]
  if (all(is.na(m))) return(dplyr::tibble())
  
  lvls <- sort(unique(m[!is.na(m)]))
  if (!is.null(exclude_levels)) lvls <- setdiff(lvls, exclude_levels)
  if (length(lvls) == 0) return(dplyr::tibble())
  
  out <- lapply(lvls, function(lvl) {
    # onset = value equals lvl but previous sample is different (or NA)
    on_idx <- which(m == lvl & dplyr::lag(m, default = NA) != lvl)
    if (length(on_idx) == 0) return(NULL)
    
    tvec <- df[[time_col]][on_idx]
    
    # enforce minimal spacing (min_interval) between onsets
    keep   <- logical(length(on_idx))
    last_t <- -Inf
    for (i in seq_along(on_idx)) {
      if ((tvec[i] - last_t) >= min_interval) {
        keep[i] <- TRUE
        last_t  <- tvec[i]
      }
    }
    if (!any(keep)) return(NULL)
    
    dplyr::tibble(
      event_time = tvec[keep],
      event_idx  = on_idx[keep],
      event_var  = paste0("motif_", as.character(lvl)),
      event_type = "onset"
    )
  })
  
  dplyr::bind_rows(out)
}

# ---- Compute PETH windows with per-event (within-window) scaling ----
# For each event, extracts a window [−peth_window, +peth_window] around event_time and z-scores the FP signal using only that window (per-event scaling).
compute_peth_fp <- function(df, events_df, signals, peth_window, frame.behavior) {
  if (nrow(events_df) == 0) return(tibble())
  
  win_frames <- round(peth_window / frame.behavior)
  out_list <- vector("list", nrow(events_df))
  
  for (i in seq_len(nrow(events_df))) {
    evt_time <- events_df$event_time[i]
    
    # Skip events too close to edges of recording
    if (evt_time - peth_window < min(df$time, na.rm = TRUE) ||
        evt_time + peth_window > max(df$time, na.rm = TRUE)) {
      next
    }
    
    win_frames <- as.integer(round(peth_window / frame.behavior))
    center_idx <- which.min(abs(df$time - evt_time))
    nor_idx    <- (-win_frames):win_frames                     
    idx_range  <- center_idx + nor_idx
    nor.time   <- nor_idx * frame.behavior
    
    # Windowed signals (raw values)
    sig_win <- df[idx_range, signals, drop = FALSE]
    
    # Per-event scaling: z-score using only this window
    scaled_win <- as.data.frame(lapply(sig_win, function(v) {
      m <- mean(v, na.rm = TRUE)
      s <- sd(v,   na.rm = TRUE)
      if (is.finite(s) && s > 0) {
        (v - m) / s
      } else {
        v - m  # zero-variance fallback: mean-center
      }
    }))
    
    sig_long <- scaled_win %>%
      mutate(nor_idx = nor_idx, nor.time = nor.time) %>%
      tidyr::pivot_longer(cols = tidyselect::all_of(signals),
                          names_to = "signal", values_to = "value") %>%
      mutate(event_time = evt_time,
             event_var  = events_df$event_var[i],
             event_type = events_df$event_type[i])
    
    out_list[[i]] <- sig_long
  }
  
  dplyr::bind_rows(out_list)
}

# ---- Overlay (mean±SEM) + per-event heatmap, stacked per signal ----
plot_peth_overlay_with_heatmaps <- function(PETH_agg, PETH_long, ev_name, video, event_type_keep = NULL) {
  # default: motifs -> "onset"; behaviors -> "high"
  if (is.null(event_type_keep)) {
    event_type_keep <- if (grepl("^motif_", ev_name)) "onset" else "high"
  }
  
  PETH_agg_ev  <- PETH_agg [PETH_agg$event_var  == ev_name & PETH_agg$event_type  %in% event_type_keep, , drop = FALSE]
  PETH_long_ev <- PETH_long[PETH_long$event_var == ev_name & PETH_long$event_type %in% event_type_keep, , drop = FALSE]
  
  sigs <- unique(PETH_long_ev$signal)
  if (length(sigs) == 0) return(NULL)
  
  stacks <- lapply(sigs, function(sig) {
    # line (mean±SEM) for this signal
    df_line <- PETH_agg_ev[PETH_agg_ev$signal == sig, , drop = FALSE]
    
    p_line <- ggplot(df_line, aes(x = nor.time, y = mean_value, color = signal)) +
      geom_ribbon(aes(ymin = mean_value - sem_value, ymax = mean_value + sem_value, fill = signal),
                  alpha = 0.25, colour = NA) +
      geom_line(linewidth = 0.9) +
      geom_vline(xintercept = 0, linetype = "dashed") +
      scico::scale_color_scico_d(palette = "roma") +
      scico::scale_fill_scico_d(palette = "roma") +
      xlim(-5, 10) +  # show central window; full PETH is ±10 s
      theme_bw() +
      theme(legend.position = "none",
            panel.grid = element_blank(),
            plot.title = element_text(hjust = 0, size = 12)) +
      labs(title = paste0(sig, " (", paste(event_type_keep, collapse = ","), ")"),
           x = NULL, y = "z")
    
    # heatmap: only this variable+type+signal
    df_heat <- PETH_long_ev[PETH_long_ev$signal == sig, , drop = FALSE]
    if (nrow(df_heat) == 0) return(p_line)
    
    ev_order <- df_heat |>
      dplyr::distinct(event_time) |>
      dplyr::arrange(event_time)  |>
      dplyr::mutate(trial_id = dplyr::row_number())
    
    df_heat <- df_heat |>
      dplyr::left_join(ev_order, by = "event_time") |>
      dplyr::mutate(trial_id = factor(trial_id, levels = ev_order$trial_id))
    
    p_heat <- ggplot(df_heat, aes(x = nor.time, y = trial_id, fill = value)) +
      geom_tile() +
      geom_vline(xintercept = 0, color = "white", linewidth = 0.4, linetype = "dashed") +
      scico::scale_fill_scico(palette = "vik", limits = c(-3, 3), oob = scales::squish) +
      xlim(-5, 10) +
      theme_bw() +
      theme(panel.grid = element_blank(),
            legend.position = "none") +
      labs(x = "Time (s)", y = NULL,
           title = paste0("trials (n=", nrow(ev_order), ")"))
    
    p_line / p_heat + patchwork::plot_layout(heights = c(1, 2))
  })
  
  patchwork::wrap_plots(stacks, ncol = 3) +
    patchwork::plot_annotation(
      title = paste0("PETH — events: ", ev_name,
                     " (", paste(event_type_keep, collapse = ","), ") — ", video)
    )
}

# ------------------ FILTER VIDEOS BY EXPERIMENT ------------------
# Only process videos annotated as 'oft_fp' in details.csv
valid_videos <- details$video[details$experiment == "oft_fp"]
valid_videos <- unique(as.character(valid_videos))

# Filter aligned files to only include those videos
files.to.read <- files.to.read[
  vapply(files.to.read, function(p) {
    video_from_results(p) %in% valid_videos
  }, logical(1))
]

message("Videos to process (experiment == 'oft_fp'): ", length(files.to.read))

if (length(files.to.read) == 0L) {
  message("No aligned videos match experiment == 'oft_fp'. Nothing to do.")
  return(invisible(NULL))
}

# ------------------ PROCESS ------------------
pb <- progress_bar$new(
  total  = length(files.to.read),
  format = "[:bar] :current/:total :percent :eta  :message"
)

for (f in seq_along(files.to.read)) {
  pb$tick(tokens = list(message = basename(files.to.read[f])))
  
  aligned_path <- files.to.read[f]
  video        <- video_from_results(aligned_path)
  
  meta_row <- details[details$video == video, ]

  if (nrow(meta_row) == 0L) {
    warning("No metadata row for video ", video, " — skipping.")
    next
  }
  if (nrow(meta_row) > 1L) {
    warning("Multiple metadata rows for video ", video, " — using first.")
    meta_row <- meta_row[1, , drop = FALSE]
  }
  
  group <- meta_row$group
  out_dir <- peth_out_dir(video)
  if (!dir.exists(out_dir)) dir.create(out_dir, recursive = TRUE)
  
  # Skip if already processed (PETH + event list exist) and not overwriting
  peth_csv_out1  <- file.path(dirname(aligned_path), paste0(video, "_peth_all_events.csv"))
  peth_csv_out2  <- file.path(dirname(aligned_path), paste0(video, "_peth_agg.csv"))
  events_csv_out <- file.path(dirname(aligned_path), paste0(video, "_events.csv"))
  if (!OVERWRITE_PETH && peth_csv_out1 %in% files.done && file.exists(events_csv_out)) next
  
  # ----- Load aligned behavior+signal -----
  df <- read.csv(aligned_path)
  
  # Available FP signal (single column: "signal")
  possible_signals <- c("signal", "speed")
  signals <- intersect(possible_signals, names(df))
  if (length(signals) == 0) {
    message("No FP signal found for ", video, ". Skipping.")
    next
  }
  
  # ----- Events from BEHAVIOR (z-episodes) -----
  events_beh <- get_behavior_episodes(
    df             = df,
    time_col       = "time",
    vars           = NULL,            # auto-detect behavior vars
    z_thr          = z_thr,
    min_interval   = min_interval,
    frame.behavior = frame.behavior,
    event_anchor   = "peak"
  )
  
  # ----- Events from MOTIF onsets -----
  events_mot <- get_motif_onsets(
    df             = df,
    time_col       = "time",
    motif_col      = "motif",
    exclude_levels = NULL,           # include all motifs
    min_interval   = min_interval
  )
  
  # Merge events; keep ordered by time
  events_all <- bind_rows(events_beh, events_mot) %>% arrange(event_time)
  
  # ---- First photometry change time (to discard early "pre-signal" events) ----
  sig_cols <- signals
  tol      <- 0.0001  # tolerance for tiny float jitter
  
  changed_any <- Reduce(`|`, lapply(sig_cols, function(cn) {
    x <- df[[cn]]
    c(
      FALSE,
      (is.na(x[-1]) != is.na(x[-length(x)])) |                      # NA status change
        (!is.na(x[-1]) & !is.na(x[-length(x)]) &                    # numeric change
           abs(x[-1] - x[-length(x)]) > tol)
    )
  }))
  
  idx <- which(changed_any)[1]
  first_change_time <- if (length(idx) == 0 || is.na(idx)) NA_real_ else df$time[idx]
  
  # Drop events that are too early relative to the first reliable FP sample
  if (!is.na(first_change_time)) {
    events_all <- subset(events_all, event_time > first_change_time + peth_window)
  }
  events_all$video <- video
  events_all$group <- group
  
  write.csv(events_all, events_csv_out, row.names = FALSE)
  
  if (nrow(events_all) == 0) {
    message("No events found for ", video)
    next
  }
  
  # ----- Compute PETH around those events for all available signals -----
  PETH_long <- compute_peth_fp(df, events_all, signals, peth_window, frame.behavior)
  if (nrow(PETH_long) == 0) {
    message("No valid PETH windows for ", video)
    next
  }
  
  # Aggregate (mean ± SEM) 
  PETH_agg <- PETH_long %>%
    dplyr::group_by(event_var, event_type, signal, nor_idx) %>%
    dplyr::summarise(
      n_events   = dplyr::n_distinct(event_time),
      mean_value = mean(value, na.rm = TRUE),
      sem_value  = sd(value,   na.rm = TRUE) / sqrt(n_events),
      .groups = "drop"
    ) %>%
    dplyr::mutate(nor.time = nor_idx * frame.behavior) %>%
    dplyr::arrange(nor_idx)
  
  # Save PETH CSVs
  PETH_long$video <- video
  PETH_long$group <- group
  PETH_agg$video  <- video
  PETH_agg$group  <- group
  
  write.csv(PETH_long, peth_csv_out1, row.names = FALSE)
  write.csv(PETH_agg,  peth_csv_out2, row.names = FALSE)
  
  # ----- Plots per event variable (overlay + heatmaps per signal) -----
  for (ev in unique(PETH_agg$event_var)) {
    et_keep <- if (grepl("^motif_", ev)) "onset" else "high"
    p <- plot_peth_overlay_with_heatmaps(PETH_agg, PETH_long, ev, video, event_type_keep = et_keep)
    if (!is.null(p)) {
      n_sig_ev <- PETH_long %>%
        dplyr::filter(.data$event_var == ev, .data$event_type %in% et_keep) %>%
        dplyr::pull(signal) %>% unique() %>% length()
      ggsave(file.path(out_dir, paste0(ev, "_PETH.pdf")),
             p, width = 12, height = max(4.5, 3 * n_sig_ev), dpi = 300)
    }
  }
  
  message(video, " — PETH done (", nrow(PETH_agg), " rows)")
}