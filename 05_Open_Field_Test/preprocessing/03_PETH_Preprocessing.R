# ============================================================
# Peri-event time histogram (PETH) analysis
# Author: Alessandro Contestabile
#
# Description:
#   - Identifies behavioral episodes from standardized kinematic variables and VAME motif transitions.
#   - Extracts event-aligned fiber photometry and locomotor speed signals.
#   - Computes peri-event time histograms (PETHs) using event-specific normalization.
#   - Calculates mean responses and standard errors across detected events.
#   - Generates event-aligned traces and heatmaps.
#
# Requirements:
#   - details.csv containing recording metadata.
#   - Frame-wise aligned behavioral and photometry data generated by the preceding preprocessing script.
#
# Outputs:
#   - <video>_events.csv: detected behavioral events.
#   - <video>_peth_all_events.csv: event-aligned signals.
#   - <video>_peth_agg.csv: mean and SEM across events.
#   - Individual PETH figures in PDF format.
#
# Notes:
#   - Behavioral episodes are identified using thresholds applied to recording-wise standardized variables.
#   - PETH signals are normalized independently within each event window.
# ============================================================

