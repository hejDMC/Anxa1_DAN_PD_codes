# Extract video name from path "results/<video>/<video>_aligned.csv".
# Fallback: strip the "_aligned.csv" suffix from filename.
video_from_results <- function(p) {
  parent <- basename(dirname(p))
  f <- basename(p)
  if (startsWith(f, parent)) parent else sub("_aligned\\.csv$", "", f)
}

