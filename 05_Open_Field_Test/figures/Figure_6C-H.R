# Safer y-limits with small padding (for cleaner boxplots)
y_lim <- function(v) {
  v <- v[is.finite(v)]
  if (!length(v)) return(c(0, 1))
  r <- range(v, na.rm = TRUE)
  pad <- max(1e-8, diff(r) * 0.04)
  c(r[1] - pad, r[2] + pad)
}

