# ------------------  STATS FOR NORMALIZED MOTIF TIME (EXP ONLY)  ------------------
# One-sample Wilcoxon test of norm vs 0 for each experiment × motif
norm_stats <- motif_norm_exp %>%
  dplyr::group_by(experiment, motif) %>%
  dplyr::summarise(
    n_mice = dplyr::n(),
    p_value = {
      x <- norm[is.finite(norm)]
      # Only test if at least 2 values and some deviation from 0
      if (length(x) >= 2 && any(x != 0, na.rm = TRUE)) {
        suppressWarnings(stats::wilcox.test(x, mu = 0)$p.value)
      } else {
        NA_real_
      }
    },
    .groups = "drop"
  ) %>%
  dplyr::mutate(
    p_adj_FDR = p.adjust(p_value, method = "fdr")
  ) %>%
  dplyr::arrange(experiment, motif)

# Save stats table
