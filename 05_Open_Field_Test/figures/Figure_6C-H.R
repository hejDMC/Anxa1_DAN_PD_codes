# Single-experiment panel builder
#   - x: ctrl vs exp
#   - y: metric
#   - adds Wilcoxon p-value only if both groups present
make_panel <- function(df_exp, exp_name, metric, ylim_vec) {
  df_exp <- df_exp %>%
    dplyr::mutate(
      ctrl.vs.exp = ifelse(is_ctrl(ctrl.vs.exp), "ctrl", "exp")
    ) %>%
    dplyr::filter(!is.na(.data[[metric]]))
  
  if (nrow(df_exp) == 0L) {
    return(ggplot() + theme_void())
  }
  
  # count ctrl / exp
  n_ctrl <- sum(df_exp$ctrl.vs.exp == "ctrl")
  n_exp  <- sum(df_exp$ctrl.vs.exp == "exp")
  title_text <- paste0("n ctrl = ", n_ctrl, "   |   n exp = ", n_exp)
  
  exp_col <- if (exp_name %in% names(exp_colors)) exp_colors[[exp_name]] else "#444444"
  both_groups <- length(unique(df_exp$ctrl.vs.exp)) > 1L
  
  p <- ggplot(df_exp, aes(x = ctrl.vs.exp, y = .data[[metric]])) +
    geom_boxplot(
      aes(fill = ctrl.vs.exp),
      outlier.shape = NA, width = 0.7,
      color = "black", linewidth = 0.3
    ) +
    geom_jitter(
      aes(color = ctrl.vs.exp),
      width = 0.15, alpha = 0.6, size = 1.5,
      show.legend = FALSE
    ) +
    scale_x_discrete(limits = c("ctrl", "exp"), drop = FALSE) +
    scale_fill_manual(
      values = c(ctrl = "lightgrey", exp = exp_col),
      guide  = "none"
    ) +
    scale_color_manual(
      values = c(ctrl = "lightgrey", exp = exp_col),
      guide  = "none"
    ) +
    scale_y_continuous(limits = ylim_vec, expand = expansion(mult = 0)) +
    labs(
      x = NULL,
      y = metric,
      title = title_text
    ) +
    theme_bw(base_size = 12) +
    theme(
      panel.grid      = element_blank(),
      legend.position = "none",
      plot.title      = element_text(size = 11, face = "bold", hjust = 0.5),
      axis.text.x     = element_text(vjust = 0.5),
      plot.margin     = margin(2, 4, 2, 4)
    )
  
  if (both_groups) {
    p <- p + ggpubr::stat_compare_means(
      method = "wilcox.test",
      label  = "p.format", 
      label.y = 0.1
    )
  }
  p
}

