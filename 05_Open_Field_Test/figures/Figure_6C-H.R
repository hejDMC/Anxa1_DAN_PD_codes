# Long format: one row per mouse × motif
motif_long <- sum_mouse %>%
  dplyr::select(
    mouse.ID, group, line, sex, ctrl.vs.exp, experiment,
    dplyr::all_of(motif_sec_cols)
  ) %>%
  tidyr::pivot_longer(
    cols      = dplyr::all_of(motif_sec_cols),
    names_to  = "motif_col",
    values_to = "motif_sec"
  ) %>%
  dplyr::mutate(
    motif = as.integer(sub("^motif_sec_", "", motif_col))
  ) %>%
  dplyr::select(-motif_col) %>%
  # Keep only motifs that pass the global n_mice threshold
  dplyr::filter(motif %in% valid_motifs)

# Control baselines per experiment × motif
ctrl_mean <- motif_long %>%
  dplyr::filter(is_ctrl(ctrl.vs.exp)) %>%
  dplyr::group_by(experiment, motif) %>%
  dplyr::summarise(
    ctrl_mean_sec = mean(motif_sec, na.rm = TRUE),
    .groups       = "drop"
  )

# Normalization (only EXP animals):
motif_norm_exp <- motif_long %>%
  dplyr::left_join(ctrl_mean, by = c("experiment", "motif")) %>%
  dplyr::filter(!is_ctrl(ctrl.vs.exp)) %>%
  dplyr::mutate(
    norm = dplyr::if_else(
      !is.na(ctrl_mean_sec) & (motif_sec + ctrl_mean_sec) != 0,
      (motif_sec - ctrl_mean_sec)/(motif_sec + ctrl_mean_sec),
      NA_real_
    )
  ) %>%
  dplyr::filter(!is.na(norm)) %>%
  dplyr::left_join(motif_lab_df, by = "motif") %>%
  dplyr::mutate(
    # Factor with fast motifs at the top in plots
    motif = factor(motif, levels = rev(motif_levels_fast2slow))
  )

