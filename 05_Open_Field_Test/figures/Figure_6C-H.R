# ------------------  WILCOXON STATS TABLE (FDR)  ------------------
stats_tbl <- experiments |>
  purrr::map_df(function(exp_name) {
    df_exp <- dplyr::filter(plot_df, experiment == exp_name) |>
      dplyr::mutate(
        ctrl.vs.exp = ifelse(is_ctrl(ctrl.vs.exp), "ctrl", "exp")
      )
    
    metrics <- c("mean_speed", "mean_ang_speed", "immobile_time_s")
    purrr::map_df(metrics, function(met) {
      sub <- dplyr::filter(df_exp, !is.na(.data[[met]]))
      has_both <- length(unique(sub$ctrl.vs.exp)) > 1L
      
      if (!has_both) {
        return(
          tibble(
            experiment = exp_name,
            metric     = met,
            n_ctrl     = sum(sub$ctrl.vs.exp == "ctrl"),
            n_exp      = sum(sub$ctrl.vs.exp == "exp"),
            p_value    = NA_real_
          )
        )
      }
      
      x <- sub %>%
        dplyr::filter(ctrl.vs.exp == "ctrl") %>%
        dplyr::pull(.data[[met]])
      y <- sub %>%
        dplyr::filter(ctrl.vs.exp == "exp") %>%
        dplyr::pull(.data[[met]])
      
      wt <- suppressWarnings(
        stats::wilcox.test(x, y, alternative = "two.sided", exact = FALSE)
      )
      
      tibble(
        experiment = exp_name,
        metric     = met,
        n_ctrl     = length(x),
        n_exp      = length(y),
        p_value    = wt$p.value
      )
    })
  })

if (nrow(stats_tbl)) {
