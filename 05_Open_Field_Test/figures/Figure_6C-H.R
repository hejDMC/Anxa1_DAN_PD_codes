# ============================================================
# Figure 6C–H — Open-field behavioral and motif analyses
# Author: Alessandro Contestabile
#
# Description:
#   - Compares locomotor speed, angular velocity, and immobility between control and experimental mice.
#   - Performs Wilcoxon rank-sum tests with FDR correction.
#   - Quantifies behavioral motif usage across experiments.
#   - Normalizes motif duration relative to the corresponding experimental control group.
#   - Performs one-sample Wilcoxon tests on normalized motif values with FDR correction.
#   - Generates behavioral comparison and motif usage figures.
#
# Requirements:
#   - summary_per_mouse.csv generated during preprocessing.
#   - mean_speed_per_motif_overall.csv generated by the Figure 5 analysis script.
#
# Outputs:
#   - figure_6C.pdf: behavioral comparisons.
#   - figure_6H.pdf: normalized motif usage.
#   - stats_figure_6C_wilcoxon_FDR.csv
#   - stats_figure_6H_wilcoxon_FDR.csv
#   - motif_norm_long_per_mouse.csv
#   - motif_norm_summary_exp_motif.csv
#
# Notes:
#   - Fiber photometry recordings (oft_fp) are excluded.
#   - Motifs are ordered by their overall mean speed.
#   - Motif usage is normalized as:(experimental - control) / (experimental + control) using the experiment-specific control mean.
# ============================================================

