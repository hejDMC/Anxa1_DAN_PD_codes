# ============================================================
# Extended Data Figure 6A — Photometry signals versus speed
# Author: Alessandro Contestabile
#
# Description:
#   - Quantifies the relationship between locomotor speed and fiber-photometry signals during open-field behavior.
#   - Aggregates speed and photometry measurements using multiple temporal bin sizes (0.1, 0.2, 0.5, and 1 s).
#   - Groups measurements into discrete speed bins.
#   - Generates circularly shuffled photometry controls to assess temporal relationships between signals and locomotor speed.
#   - Computes per-recording and group-level mean signals with standard errors of the mean (SEM).
#   - Compares real and shuffled signals across groups and temporal resolutions.
#
# Requirements:
#   - Frame-wise *_aligned.csv files generated during OFT preprocessing.
#   - Columns: time, speed, signal, group, mouse.ID.
#
# Outputs:
#   - dopamine_vs_speed_mean_sem.pdf
#   - dopamine_vs_speed_mean_sem.png
#   - dopamine_vs_speed_agg_bins_group_level.csv
#
# Notes:
#   - Temporal bins: 0.1, 0.2, 0.5, and 1 second.
#   - Speed bins have a width of 2 cm/s.
#   - Shuffled signals are generated by circular shifts of at least 10% of the recording length.
#   - Shuffled results are pooled across temporal bin sizes.
#   - Group summaries represent mean ± SEM across contributing recordings.
# ============================================================

# ----------------- CLEAN ENVIRONMENT ------------------
rm(list = ls())

# ------------------ LIBRARIES ------------------
suppressPackageStartupMessages({
  library(tidyverse)
  library(mgcv)    
  library(energy)  
  library(ggpubr)  
})

# ------------------ SETTINGS ------------------
set.seed(2301)
DATA_DIR     <- "path/to/VAME_project/results"
ANALYSIS_DIR <- file.path(DATA_DIR, "analysis")
BIN_SIZES    <- c(0.1, 0.2, 0.5, 1)   # seconds

dir.create(ANALYSIS_DIR, showWarnings = FALSE, recursive = TRUE)

# Groups of interest
GROUPS_OF_INTEREST <- c("anxa1-flp", "dLight_dStr", "dLight_vStr", "dat-cre")

# ------------ HELPER: circular shuffle with minimum shift -------------
circular_shuffle <- function(x, min_frac = 0.1) {
  n <- length(x)
  if (n <= 2) return(x)
  
  min_shift <- ceiling(n * min_frac)
  if (min_shift >= n) {
    return(sample(x))
  }
  
  k <- sample(min_shift:n, 1)
  c(x[k:n], x[1:(k - 1)])
}

# ------------------ LOAD ALL *_aligned.csv ------------------
aligned_files <- list.files(
  DATA_DIR,
  pattern   = "_aligned.csv$",
  recursive = TRUE,
  full.names = TRUE
)

df_all <- list()  # list to collect per-file, per-bin_size data

# progress bar
pb <- txtProgressBar(min = 0, max = length(aligned_files), style = 3)

for (i in seq_along(aligned_files)) {
  f <- aligned_files[i]
  setTxtProgressBar(pb, i)
  
  # video name is the folder name
  video_name <- basename(dirname(f))
  
  # load file; skip on error
  df <- tryCatch(read.csv(f), error = function(e) NULL)
  if (is.null(df)) next
  
  # must have signal, time, speed
  if (!("signal" %in% names(df))) {
    message("Skipping (no signal): ", basename(f))
    next
  }
  if (!("time" %in% names(df)) || !("speed" %in% names(df))) {
    message("Skipping (no time/speed): ", basename(f))
    next
  }
  
  # group & mouse.ID
  if (!("group" %in% names(df)))  df$group    <- "unknown"
  if (!("mouse.ID" %in% names(df))) df$mouse.ID <- basename(f)
  
  # make sure we have a video variable
  if (!("video" %in% names(df))) df$video <- video_name
  
  # keep only groups of interest
  if (!any(df$group %in% GROUPS_OF_INTEREST)) next
  df <- df %>% dplyr::filter(group %in% GROUPS_OF_INTEREST)
  
  # ensure numeric
  df$time   <- as.numeric(df$time)
  df$speed  <- as.numeric(df$speed)
  df$signal <- as.numeric(df$signal)
  
  if (nrow(df) < 10) {
    message("Skipping (too few rows): ", basename(f))
    next
  }
  
  # ----- LOOP OVER TEMPORAL BIN SIZES -----
  for (bin in BIN_SIZES) {
    # define a temporal bin ID by dividing time and flooring
    df$bin_id <- floor(df$time / bin)
    
    # REAL data: average speed and signal within each temporal bin
    tmp <- df %>%
      dplyr::group_by(group, video, mouse.ID, bin_size = bin, bin_id) %>%
      dplyr::summarise(
        binned_speed  = mean(speed,  na.rm = TRUE),
        binned_signal = mean(signal, na.rm = TRUE),
        .groups = "drop"
      ) %>%
      dplyr::mutate(source = "real")
    
    # SHUFFLED control (circular with min shift)
    df$signal_shuf <- circular_shuffle(df$signal, min_frac = 0.1)
    
    tmp_shuf <- df %>%
      dplyr::group_by(group, video, mouse.ID, bin_size = bin, bin_id) %>%
      dplyr::summarise(
        binned_speed  = mean(speed,       na.rm = TRUE),
        binned_signal = mean(signal_shuf, na.rm = TRUE),
        .groups = "drop"
      ) %>%
      dplyr::mutate(source = "shuffled")
    
    # collect
    df_all[[length(df_all) + 1L]] <- tmp
    df_all[[length(df_all) + 1L]] <- tmp_shuf
  }
}

close(pb)

# ------------------ COMBINE ALL FILES ------------------
if (!length(df_all)) {
  stop("No valid aligned files with signal + groups of interest found.")
}

bigdf <- dplyr::bind_rows(df_all)

message("Data loaded: ", nrow(bigdf), " binned points across groups: ",
        paste(unique(bigdf$group), collapse = ", "))

# labeled factor for bin size (for facets)
bigdf$bin_size_f <- factor(
  bigdf$bin_size,
  levels = sort(unique(bigdf$bin_size)),
  labels = paste0(sort(unique(bigdf$bin_size)), " s")
)

# ------------------ SPEED BINS: ADJUSTABLE ROUNDING ------------------
BIN_WIDTH <- 2   # <<< CHANGE THIS (1, 2, 3, ...)

bigdf <- bigdf %>%
  dplyr::mutate(
    speed_bin = round(binned_speed / BIN_WIDTH) * BIN_WIDTH,
    
    # optional: enforce natural numbers (no negative speed bins)
    speed_bin = pmax(speed_bin, 0)
  )

# ------------------ AGGREGATION: PER-MOUSE, PER-VIDEO, PER SPEED BIN -------------
agg_bins <- bigdf %>%
  dplyr::filter(
    is.finite(binned_speed),
    is.finite(binned_signal),
    !is.na(speed_bin)
  ) %>%
  dplyr::group_by(group, bin_size_f, source, video, mouse.ID, speed_bin) %>%
  dplyr::summarise(
    speed_bin_center = mean(binned_speed,  na.rm = TRUE),
    signal_bin_mean  = mean(binned_signal, na.rm = TRUE),
    n_points         = dplyr::n(),
    signal_bin_sem   = sd(binned_signal, na.rm = TRUE) / sqrt(n_points),
    .groups = "drop"
  )

# ------------------ POOL SHUFFLED ACROSS BIN SIZES ------------------

# ---- Skeep REAL exactly as it is ----
agg_real <- agg_bins %>%
  dplyr::filter(source == "real")

# ---- pool SHUFFLED across bin sizes (average per mouse/video/speed_bin) ----
agg_shuf_pooled <- agg_bins %>%
  dplyr::filter(source == "shuffled") %>%
  dplyr::group_by(group, source, video, mouse.ID, speed_bin) %>%
  dplyr::summarise(
    speed_bin_center = mean(speed_bin_center, na.rm = TRUE),
    signal_bin_mean  = mean(signal_bin_mean,  na.rm = TRUE),
    n_points         = sum(n_points),     # total contributing bins
    signal_bin_sem   = sd(signal_bin_mean, na.rm = TRUE) / 
      sqrt(dplyr::n()),   # SEM across bin sizes
    .groups = "drop"
  ) %>%
  dplyr::mutate(
    bin_size_f = "shuffled"   # label for faceting later
  )

# ---- recombine REAL + POOLED SHUFFLED ----
agg_bins_merged <- dplyr::bind_rows(
  agg_real,
  agg_shuf_pooled
)

# ------------------ GROUP-LEVEL SUMMARY FOR PLOTTING -----------------------------
agg_plot <- agg_bins_merged %>%
  dplyr::group_by(group, bin_size_f, source, speed_bin) %>%
  dplyr::summarise(
    # mean of speed_bin_center (should be ~ the integer speed_bin)
    speed_bin_center = mean(speed_bin_center, na.rm = TRUE),
    signal_mean      = mean(signal_bin_mean,  na.rm = TRUE),
    n_cells          = dplyr::n(),
    signal_sem       = sd(signal_bin_mean, na.rm = TRUE) /
      sqrt(n_cells),
    .groups = "drop"
  )

# save plotting summary
write.csv(
  agg_plot,
  file = file.path(ANALYSIS_DIR, "dopamine_vs_speed_agg_bins_group_level.csv"),
  row.names = FALSE
)

# ------------------ VIDEO COUNTS (INFO ONLY) -------------------------------------
# Number of videos contributing per group × bin_size (for annotation if needed)
video_counts <- bigdf %>%
  dplyr::group_by(group, bin_size_f) %>%
  dplyr::summarise(
    n_video = dplyr::n_distinct(video),
    .groups = "drop"
  )

# ------------------ FILTER: keep only speed_bin ≤ 15 ------------------
agg_plot <- agg_plot %>%
  dplyr::filter(speed_bin <= 14)

# ------------------ PLOT ----------------------------
# First ensure the order of bin_size_f so colors map correctly
agg_plot$bin_size_f <- factor(
  agg_plot$bin_size_f,
  levels = c("0.1 s", "0.2 s", "0.5 s", "1 s", "shuffled")
)

# Color palette for 6 bin sizes (your specified colors + pooled as lightgrey)
bin_colors <- c(
  "0.1 s" = "#5BC0BE",
  "0.2 s"  = "#758BFD",
  "0.5 s" = "#3A506B",
  "1 s"  = "#0B132B",
  "shuffled" = "lightgrey"
)

# ------------------ PLOT ------------------
p <- ggplot(
  agg_plot,
  aes(x = speed_bin, y = signal_mean,
      colour = bin_size_f, fill = bin_size_f)
) +
  
  # SEM ribbon
  geom_ribbon(
    aes(
      ymin = signal_mean - signal_sem,
      ymax = signal_mean + signal_sem,
      fill = bin_size_f
    ),
    alpha = 0.20,
    colour = NA
  ) +
  
  # Mean line
  geom_line(size = 1) +
  
  # Apply manual colors
  scale_fill_manual(values = bin_colors) +
  scale_colour_manual(values = bin_colors) +
  
  facet_wrap(group ~ ., ncol = 2) +
  
  labs(
    title  = "Dopamine vs Speed (rounded speed bins; mean ± SEM ribbon)",
    x      = "Speed (cm/s)",
    y      = "Signal (z)",
    colour = "Bin size",
    fill   = "Bin size"
  ) +
  
  theme_bw() +
  theme(
    panel.grid = element_blank(),
    strip.text = element_text(size = 12)
  )

print(p)

# Save figure
ggsave(
  filename = file.path(ANALYSIS_DIR, "dopamine_vs_speed_mean_sem.pdf"),
  plot     = p,
  width    = 8,
  height   = 8
)