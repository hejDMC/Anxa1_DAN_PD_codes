# ============================================================
# Figure 6M — Behavioral motif transition networks
# Author: Alessandro Contestabile
#
# Description:
#   - Reconstructs directed behavioral motif transition networks from VAME-derived sequence features.
#   - Compares control and experimental mice within selected open-field experiments.
#   - Represents motif usage as node size and transition probability as edge thickness.
#   - Colors motifs according to manually assigned behavioral categories.
#   - Uses a shared network layout to facilitate comparisons between experimental groups.
#   - Compares transition probabilities using Wilcoxon rank-sum tests with FDR correction.
#
# Requirements:
#   - vame_sequence_features.csv generated by the XGBoost feature-extraction script.
#   - summary_annotations.csv containing motif identities and behavioral annotations.
#
# Outputs:
#   - figure_6M_selected.pdf
#   - stats_figure_6M_wilcoxon_FDR_all_transitions.csv
#
# Notes:
#   - Experiments and behavioral categories can be selected in the settings section below.
#   - Only transitions with mean probability > 0.05 are displayed in the network.
#   - Network coordinates are generated using the Fruchterman-Reingold layout with a fixed seed.
# ============================================================

# ------------------ CLEAN ENVIRONMENT ------------------
rm(list = ls())
invisible(gc())

# ------------------ LIBRARIES ------------------
suppressPackageStartupMessages({
  library(dplyr)
  library(tidyr)
  library(stringr)
  library(ggplot2)
  library(igraph)
  library(patchwork)
})

# ------------------ USER-CONTROLLED PARAMETERS ------------------
# choose one or more experiments
experiments_to_use    <- c("oft_Tetx")

# NOTE: Adjust here
behaviors_to_include  <- c("Walking", "Walking/sniffing",
                           "Turning", "Rearing",
                           "Stationary", "Grooming", "Sniffing")

# Behavior levels and colors
beh_levels <- c(
  "Grooming",
  "Sniffing",
  "Stationary",
  "Rearing",
  "Turning",
  "Walking",
  "Walking/sniffing"
)

beh_cols <- c(
  "#B56576",
  "#6D597A",
  "#BD9CC0",
  "#EAAC8B",
  "#F5E8D0",
  "#355070",
  "#A0ABBF"
)
names(beh_cols) <- beh_levels

# ------------------ PATHS ------------------
base_dir      <- "path/to/VAME_project"
features_file <- file.path(base_dir, "results", "vame_sequence_features.csv")
annot_file    <- file.path(base_dir, "summary_annotations.csv")
analysis_dir  <- file.path(base_dir, "results", "analysis")

if (!dir.exists(analysis_dir)) {
  dir.create(analysis_dir, recursive = TRUE, showWarnings = FALSE)
}

# Reproducible network layout
set.seed(2391)

# ------------------ LOAD DATA ------------------
vame  <- read.csv(features_file, check.names = FALSE)
annot_raw <- read.csv(annot_file, check.names = FALSE)

# ------------------ CLEAN & STANDARDIZE ANNOTATIONS -----------
# - harmonize "Walking/Sniffing" -> "Walking/sniffing"
# - enforce factor levels for behavior
annot <- annot_raw %>%
  mutate(
    behavior = dplyr::case_when(
      behavior %in% c("Walking/Sniffing", "Walking/sniffing") ~ "Walking/sniffing",
      TRUE ~ as.character(behavior)
    ),
    behavior = factor(behavior, levels = beh_levels)
  )

# ------------------ FILTER EXPERIMENTS & SELECT MOTIFS --------
vame_sel <- vame %>%
  mutate(experiment = trimws(experiment)) %>%
  dplyr::filter(experiment %in% experiments_to_use)

# Motifs whose annotation behavior is in behaviors_to_include
motifs_sel <- annot %>%
  dplyr::filter(behavior %in% behaviors_to_include) %>%
  pull(motif) %>%
  sort()

motifs_sel

# ------------------ NODE DATA: MOTIF USAGE (SECONDS) ----------
node_usage <- vame_sel %>%
  select(experiment, ctrl.vs.exp, starts_with("motif_")) %>%
  pivot_longer(
    cols      = matches("^motif_[0-9]+_sec$"),
    names_to  = "motif_name",
    values_to = "sec"
  ) %>%
  mutate(
    motif = as.integer(stringr::str_extract(motif_name, "(?<=motif_)\\d+"))
  ) %>%
  dplyr::filter(motif %in% motifs_sel) %>%
  group_by(experiment, ctrl.vs.exp, motif) %>%
  summarise(usage_sec = mean(sec, na.rm = TRUE), .groups = "drop")

# ------------------ EDGE DATA: TRANSITION PROBABILITIES -------
edge_prob_mice <- vame_sel %>%
  select(experiment, ctrl.vs.exp, mouse.ID, starts_with("p_m")) %>%
  pivot_longer(
    cols      = starts_with("p_m"),
    names_to  = "edge",
    values_to = "prob"
  ) %>%
  mutate(
    from = as.integer(str_match(edge, "^p_m(\\d+)_to_m(\\d+)$")[, 2]),
    to   = as.integer(str_match(edge, "^p_m(\\d+)_to_m(\\d+)$")[, 3])
  ) %>%
  dplyr::filter(!is.na(from), !is.na(to)) %>%
  dplyr::filter(from %in% motifs_sel,
                to   %in% motifs_sel) 

edge_prob <- vame_sel %>%
  select(experiment, ctrl.vs.exp, starts_with("p_m")) %>%
  pivot_longer(
    cols      = starts_with("p_m"),
    names_to  = "edge",
    values_to = "prob"
  ) %>%
  mutate(
    from = as.integer(str_match(edge, "^p_m(\\d+)_to_m(\\d+)$")[, 2]),
    to   = as.integer(str_match(edge, "^p_m(\\d+)_to_m(\\d+)$")[, 3])
  ) %>%
  dplyr::filter(!is.na(from), !is.na(to)) %>%
  dplyr::filter(from %in% motifs_sel,
         to   %in% motifs_sel) %>%
  group_by(experiment, ctrl.vs.exp, from, to) %>%
  summarise(prob = mean(prob, na.rm = TRUE), .groups = "drop") %>%
  mutate(prob = ifelse(is.na(prob), 0, prob)) %>%
  dplyr::filter(prob > 0.05)

# ------------------ EDGE STATS: CTRL vs EXP ------------------
# Non-parametric Wilcoxon test per directed edge + FDR correction

edge_stats <- edge_prob_mice %>%
  mutate(
    edge_id = paste0("m", from, "_to_m", to),
    group  = as.factor(ctrl.vs.exp)
  ) %>%
  group_by(from, to, edge_id) %>%
  filter(n_distinct(group) == 2) %>%
  summarise(
    n_ctrl = sum(group == "ctrl", na.rm = TRUE),
    n_exp  = sum(group == "exp",  na.rm = TRUE),
    
    mean_ctrl = mean(prob[group == "ctrl"], na.rm = TRUE),
    mean_exp  = mean(prob[group == "exp"],  na.rm = TRUE),
    
    median_ctrl = median(prob[group == "ctrl"], na.rm = TRUE),
    median_exp  = median(prob[group == "exp"],  na.rm = TRUE),
    
    delta_mean   = mean_exp - mean_ctrl,
    delta_median = median_exp - median_ctrl,
    
    p_value = tryCatch(
      wilcox.test(prob ~ group, exact = FALSE)$p.value,
      error = function(e) NA_real_
    ),
    
    .groups = "drop"
  ) %>%
  mutate(
    p_adj_fdr = p.adjust(p_value, method = "fdr"),
    signif_fdr = case_when(
      p_adj_fdr < 0.001 ~ "***",
      p_adj_fdr < 0.01  ~ "**",
      p_adj_fdr < 0.05  ~ "*",
      TRUE ~ "ns"
    )
  ) %>%
  arrange(p_adj_fdr)

# Significant edges only
edge_stats_sig <- edge_stats %>%
  filter(p_adj_fdr < 0.05)

# Inspect results
edge_stats_sig

write.csv(
  edge_stats_sig,
  file.path(analysis_dir, "stats_figure_6M_wilcoxon_FDR_all_transitions.csv"),
  row.names = FALSE
)


# ------------------ COMMON LAYOUT FOR NODES -------------------
# Use all edges (pooled across experiments & groups) to get a single layout
edges_for_layout <- edge_prob %>%
  group_by(from, to) %>%
  summarise(weight = mean(prob), .groups = "drop")

if (nrow(edges_for_layout) == 0L) {
  stop("No edges for layout (check selected experiments / behaviors).")
}

g <- graph_from_data_frame(
  d = edges_for_layout,
  directed = TRUE,
  vertices = data.frame(motif = motifs_sel)
)

lay <- layout_with_fr(g)  # Fruchterman–Reingold
lay_df <- as.data.frame(lay)
colnames(lay_df) <- c("x", "y")

layout_df <- data.frame(
  motif = motifs_sel,
  x     = lay_df$x,
  y     = lay_df$y
)

# ------------------ ADD BEHAVIOR ANNOTATION TO NODES ----------
annot_beh <- annot %>%
  select(motif, behavior)

nodes_plot <- node_usage %>%
  left_join(layout_df,  by = "motif") %>%
  left_join(annot_beh,  by = "motif") %>%
  mutate(
    ctrl.vs.exp = factor(ctrl.vs.exp, levels = c("ctrl", "exp")),
    experiment  = factor(experiment,    levels = experiments_to_use),
    behavior    = factor(behavior, levels = beh_levels)  # ensure consistent levels
  )

edges_plot <- edge_prob %>%
  left_join(layout_df %>%
              rename(from = motif,
                     x_from = x,
                     y_from = y),
            by = "from") %>%
  left_join(layout_df %>%
              rename(to = motif,
                     x_to = x,
                     y_to = y),
            by = "to") %>%
  mutate(
    ctrl.vs.exp = factor(ctrl.vs.exp, levels = c("ctrl", "exp")),
    experiment  = factor(experiment, levels = experiments_to_use)
  )

# ------------------ PLOTTING FUNCTION PER EXPERIMENT ----------
plot_transition_network <- function(exp_name) {
  
  nodes_exp <- nodes_plot %>% dplyr::filter(experiment == exp_name)
  edges_exp <- edges_plot %>% dplyr::filter(experiment == exp_name)
  
  ggplot() +
    # arrows: transition probabilities
    geom_segment(
      data = edges_exp,
      aes(x = x_from, y = y_from,
          xend = x_to, yend = y_to,
          linewidth = prob),
      arrow    = arrow(length = unit(3, "mm"), type = "closed"),
      lineend  = "round",
      alpha    = 0.85,
      colour   = "grey30"
    ) +
    # nodes: motif usage (seconds), color-coded by behavior
    geom_point(
      data  = nodes_exp,
      aes(x = x, y = y, size = usage_sec, fill = behavior),
      shape  = 21,
      colour = "black",
      stroke = 0.4
    ) +
    # motif labels
    geom_text(
      data = nodes_exp,
      aes(x = x, y = y, label = motif),
      vjust = -1.0,
      size  = 3
    ) +
    coord_equal() +
    facet_wrap(~ ctrl.vs.exp) +
    scale_size_continuous(
      name  = "Motif usage (sec)",
      range = c(2.5, 10)
    ) +
    scale_linewidth_continuous(
      name  = "Transition prob.",
      range = c(0.3, 3)
    ) +
    scale_fill_manual(
      name   = "Behavior",
      values = beh_cols,
      drop   = FALSE
    ) +
    ggtitle(exp_name) +
    theme_void(base_size = 11) +
    theme(
      legend.position = "right",
      strip.text      = element_text(face = "bold"),
      plot.title      = element_text(hjust = 0.5, face = "bold")
    )
}

# ------------------ BUILD PATCHWORK OVER EXPERIMENTS ----------
plots_list <- lapply(experiments_to_use, plot_transition_network)
names(plots_list) <- experiments_to_use

p_combined <- wrap_plots(plots_list, ncol = 1)
p_combined

# ------------------ SAVE ------------------
out_file <- file.path(
  analysis_dir,
  paste0("figure_6M_selected.pdf")
)
ggsave(out_file, p_combined,
       width  = 18 * length(plots_list),
       height = 12)
