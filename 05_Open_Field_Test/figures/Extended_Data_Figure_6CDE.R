
# ============================================================
# Extended Data Figure 6C–E — VAME motif episode durations
# Author: Alessandro Contestabile
#
# Description:
#   - Characterizes the temporal duration of behavioral motifs identified using VAME.
#   - Calculates mean episode duration, variability, and the fraction of short episodes for each motif.
#   - Examines the relationship between short-episode frequency and mean locomotor speed.
#   - Divides recordings into four temporal quarters to examine changes in motif duration over time.
#   - Generates summary plots of episode durations and short-episode proportions.
#
# Requirements:
#   - motif_episodes.csv generated by Figure_5D-H.R.
#   - mean_speed_per_motif_overall.csv generated by Figure_5D-H.R.
#
# Outputs:
#   - motif_episode_length_summary.csv
#   - Extended_Data_Figure_6CDE.pdf
#
# Notes:
#   - Short episodes are defined as durations < 150 ms.
#   - Episode statistics are pooled across recordings.
#   - Recording quarters are defined separately for each video.
#   - Episodes crossing quarter boundaries are divided into segments according to their temporal overlap.
#   - SEM is calculated across episodes or segments, rather than across individual mice.
# ============================================================


# ------------------ CLEAN ENV ------------------
rm(list = ls()); invisible(gc())

# ------------------ LIBRARIES ------------------
suppressPackageStartupMessages({
  library(tidyverse)
  library(patchwork)
})

# ------------------ PATHS & SETTINGS ------------------
OUT_ROOT     <- "path/to/VAME_project/results"
ANALYSIS_DIR <- file.path(OUT_ROOT, "analysis")

episodes_path   <- file.path(ANALYSIS_DIR, "motif_episodes.csv")
mean_speed_path <- file.path(ANALYSIS_DIR, "mean_speed_per_motif_overall.csv")

if (!file.exists(episodes_path)) {
  stop("motif_episodes.csv not found at: ", episodes_path)
}
if (!file.exists(mean_speed_path)) {
  stop("mean_speed_per_motif_overall.csv not found at: ", mean_speed_path)
}

# Threshold for “non-biologically short” episodes (seconds)
SHORT_THR_SEC <- 0.15   # 150 ms

# ------------------ LOAD DATA ------------------
episodes      <- readr::read_csv(episodes_path,   show_col_types = FALSE)
mean_speed_df <- readr::read_csv(mean_speed_path, show_col_types = FALSE)

req_cols <- c("motif", "motif_length", "video", "mouse.ID",
              "experiment", "group", "start_time", "end_time")
miss <- setdiff(req_cols, names(episodes))
if (length(miss)) {
  stop("Missing required columns in motif_episodes.csv: ", paste(miss, collapse = ", "))
}

if (!all(c("motif", "mean_speed_motif") %in% names(mean_speed_df))) {
  stop("mean_speed_per_motif_overall.csv must contain columns 'motif' and 'mean_speed_motif'.")
}

# Basic cleaning
episodes <- episodes %>%
  dplyr::filter(
    !is.na(motif),
    !is.na(motif_length),
    motif_length > 0,
    !is.na(start_time),
    !is.na(end_time)
  )

# ------------------ SUMMARY STATS PER MOTIF (ALL PERIODS) ------------------
episode_summary <- episodes %>%
  dplyr::group_by(motif) %>%
  dplyr::summarise(
    n_episodes        = dplyr::n(),
    n_mice            = dplyr::n_distinct(mouse.ID),
    mean_length_sec   = mean(motif_length,   na.rm = TRUE),
    sd_length_sec     = sd(motif_length,     na.rm = TRUE),
    sem_length_sec    = sd_length_sec / sqrt(n_episodes),
    median_length_sec = median(motif_length, na.rm = TRUE),
    iqr_length_sec    = IQR(motif_length,    na.rm = TRUE),
    short_frac        = mean(motif_length < SHORT_THR_SEC),
    .groups           = "drop"
  ) %>%
  dplyr::arrange(motif)

# Attach mean speed per motif
episode_summary <- episode_summary %>%
  dplyr::left_join(
    mean_speed_df %>% dplyr::select(motif, mean_speed_motif),
    by = "motif"
  )

out_summary <- file.path(ANALYSIS_DIR, "motif_episode_length_summary.csv")
readr::write_csv(episode_summary, out_summary)
message("Saved: ", out_summary)

# ------------------ ORDER MOTIFS USING FIGURE B (DESC short_frac) ------------------
motif_order <- episode_summary %>%
  dplyr::arrange(dplyr::desc(short_frac)) %>%
  dplyr::pull(motif)

episode_summary <- episode_summary %>%
  dplyr::mutate(motif_f = factor(motif, levels = motif_order))

# ------------------ FIGURE A (ALL PERIODS): MEAN ± SEM DURATION ------------------
p_mean_sem <- ggplot(episode_summary,
                     aes(x = motif_f, y = mean_length_sec)) +
  geom_point(size = 1.8) +
  geom_errorbar(aes(ymin = mean_length_sec - sem_length_sec,
                    ymax = mean_length_sec + sem_length_sec),
                width = 0.2) +
  labs(
    title = "VAME motif episode durations (mean ± SEM; all periods)",
    x     = "Motif",
    y     = "Episode duration (s, mean ± SEM)"
  ) +
  coord_flip() +
  theme_classic(base_size = 12)

# ------------------ FIGURE B (ALL PERIODS): FRACTION SHORT, COLORED BY SPEED ------------------
p_short <- ggplot(episode_summary,
                  aes(x = motif_f, y = short_frac,
                      fill = mean_speed_motif)) +
  geom_col() +
  scale_fill_viridis_c(
    name = "Mean speed\n(cm/s)",
    option = "B"
  ) +
  labs(
    title = paste0("Fraction of episodes shorter than ",
                   SHORT_THR_SEC * 1000, " ms (all periods)"),
    x     = "Motif",
    y     = "Proportion of short episodes"
  ) +
  coord_flip() +
  theme_classic(base_size = 12) +
  theme(
    legend.position      = c(0.98, 0.98),   # (x, y) in NPC: 0–1 range
    legend.justification = c(1, 1),         # anchor legend’s top-right corner
    legend.background    = element_rect(fill = alpha("white", 0.8), colour = NA),
    legend.key           = element_rect(fill = NA, colour = NA)
  )

# ============================================================
# PER-QUARTER ANALYSIS (4 PERIODS PER VIDEO)
# ============================================================
episodes_quarters <- episodes %>%
  dplyr::group_by(video) %>%
  dplyr::group_modify(function(df, key) {
    
    total_dur <- max(df$end_time, na.rm = TRUE)
    q_len     <- total_dur / 4
    
    quarters <- tibble::tibble(
      period  = factor(1:4, levels = 1:4,
                       labels = c("Q1","Q2","Q3","Q4")),
      q_start = (0:3) * q_len,
      q_end   = (1:4) * q_len
    )
    
    df_ep <- df %>%
      dplyr::select(mouse.ID, experiment, group,
                    motif, start_time, end_time, motif_length)
    
    df_cross <- tidyr::crossing(df_ep, quarters) %>%
      dplyr::mutate(
        overlap_start = pmax(start_time, q_start),
        overlap_end   = pmin(end_time,   q_end),
        overlap_len   = pmax(0, overlap_end - overlap_start)
      ) %>%
      dplyr::filter(overlap_len > 0)
    
    df_cross
  }) %>%
  dplyr::ungroup()

episode_summary_q <- episodes_quarters %>%
  dplyr::group_by(period, motif) %>%
  dplyr::summarise(
    n_segments        = dplyr::n(),
    mean_length_sec   = mean(overlap_len, na.rm = TRUE),
    sd_length_sec     = sd(overlap_len,   na.rm = TRUE),
    sem_length_sec    = sd_length_sec / sqrt(n_segments),
    median_length_sec = median(overlap_len, na.rm = TRUE),
    short_frac        = mean(overlap_len < SHORT_THR_SEC),
    .groups           = "drop"
  ) %>%
  dplyr::arrange(period, motif) %>%
  dplyr::left_join(
    episode_summary %>% dplyr::select(motif, mean_speed_motif),
    by = "motif"
  ) %>%
  dplyr::mutate(
    motif_f = factor(motif, levels = motif_order)
  )

# ------------------ FIGURE C (BY PERIOD): MEAN ± SEM ------------------
p_mean_sem_q <- ggplot(episode_summary_q,
                       aes(x = motif_f, y = mean_length_sec,
                           group = period, colour = period)) +
  geom_point(size = 1.3, position = position_dodge(width = 0.6)) +
  geom_errorbar(aes(ymin = mean_length_sec - sem_length_sec,
                    ymax = mean_length_sec + sem_length_sec),
                width = 0.2,
                position = position_dodge(width = 0.6)) +
  labs(
    title = "Motif episode durations (mean ± SEM) across video quarters",
    x     = "Motif ID",
    y     = "Episode duration (s, mean ± SEM)",
    colour = "Period"
  ) +
  coord_flip() +
  theme_classic(base_size = 12) +
  theme(
    legend.position      = c(0.98, 0.98),   # (x, y) in NPC: 0–1 range
    legend.justification = c(1, 1),         # anchor legend’s top-right corner
    legend.background    = element_rect(fill = alpha("white", 0.8), colour = NA),
    legend.key           = element_rect(fill = NA, colour = NA)
  )

# ------------------ FIGURE D (BY PERIOD): FRACTION SHORT, SAME STYLE AS B ------------------
p_short_q <- ggplot(episode_summary_q,
                    aes(x = motif_f, y = short_frac,
                        fill = period)) +
  geom_col(position = position_dodge2(preserve = "single", padding = 0.1), colour = NA) +
  scale_fill_brewer(palette = "PuOr") +
  labs(
    title = paste0("Fraction of episodes shorter than ",
                   SHORT_THR_SEC * 1000, " ms by video quarter"),
    x     = "Motif",
    y     = "Proportion of short episodes"
  ) +
  coord_flip() +
  theme_classic(base_size = 12) +
  theme(
    legend.position      = c(0.98, 0.98),   
    legend.justification = c(1, 1),         
    legend.background    = element_rect(fill = alpha("white", 0.8), colour = NA),
    legend.key           = element_rect(fill = NA, colour = NA)
  )

# ------------------ PATCHWORK ------------------
big_fig <- (p_short | p_short_q | p_mean_sem) 

ggsave(
  file.path(ANALYSIS_DIR, "Extended_Data_Figure_6CDE.pdf"),
  big_fig,
  width = 12,
  height = 6
)

message("Saved motif duration figures (overall + by period) and patchwork to: ", ANALYSIS_DIR)
