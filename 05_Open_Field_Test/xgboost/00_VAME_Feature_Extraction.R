# ------------------ CONFIG: PATHS & BASIC SETTINGS -----------
wd <- "path/to/VAME_project/results"
setwd(wd)

# Frame duration in seconds (e.g., 30 fps => 1/30 s per frame)
frame.behavior <- 1 / 30

# ------------------ MOTIF FILTERING SETTINGS -----------------
# mean_speed_per_motif_overall.csv is assumed to live under ./analysis/
mean_speed_path <- file.path(wd, "analysis", "mean_speed_per_motif_overall.csv")

# Minimum number of mice contributing to a motif in the OFT.
# Only motifs with n_mice >= MIN_MICE_PER_MOTIF will be kept.
MIN_MICE_PER_MOTIF <- 40

# Column in mean_speed_per_motif_overall.csv containing mouse counts per motif.
motif_count_col <- "n_mice"

# --- Per-motif microfeature thresholds (within sequence) -----
min_runs_per_motif  <- 5   # min runs to compute dwell stats
min_exits_per_motif <- 5   # min exits to compute exit entropy

# ============================================================
# HELPER FUNCTIONS
# ============================================================
# ------------------ USAGE & TRANSITION COUNTS (RUN-BASED) ----
compute_features_from_sequence <- function(seq_labels) {
  seq_labels <- as.integer(seq_labels)
  motifs     <- sort(unique(seq_labels))
  n_frames   <- length(seq_labels)
  
  # ----- Motif usage (counts, proportions) -----
  counts <- as.integer(table(factor(seq_labels, levels = motifs)))
  props  <- counts / n_frames
  
  # ----- Run-based transitions (exclude self-loops) ----------
  # Each RLE run is a "state"; transitions occur at run boundaries.
  if (n_frames >= 2) {
    rl        <- rle(seq_labels)
    run_vals  <- rl$values
    
    if (length(run_vals) >= 2) {
      from_vec <- run_vals[-length(run_vals)]
      to_vec   <- run_vals[-1L]
      
      # Transition counts from -> to
      counts_df <- tibble(from = from_vec, to = to_vec) %>%
        count(from, to, name = "n")
      
      # Full FROM x TO matrix (excluding self-loops),
      # fill missing with n = 0
      trans_counts <- expand.grid(
        from = motifs,
        to   = motifs,
        stringsAsFactors = FALSE
      ) %>%
        dplyr::filter(from != to) %>%
        left_join(counts_df, by = c("from", "to")) %>%
        mutate(n = tidyr::replace_na(n, 0L))
    } else {
      # Only one run: no exits, no transitions
      trans_counts <- expand.grid(
        from = motifs,
        to   = motifs,
        stringsAsFactors = FALSE
      ) %>%
        dplyr::filter(from != to) %>%
        mutate(n = 0L)
    }
  } else {
    # Single frame => no transitions
    trans_counts <- expand.grid(
      from = motifs,
      to   = motifs,
      stringsAsFactors = FALSE
    ) %>%
      dplyr::filter(from != to) %>%
      mutate(n = 0L)
  }
  
  list(
    motifs       = motifs,
    counts       = counts,
    props        = props,
    trans_counts = trans_counts   # from, to, n
  )
}

# ------------------ MICROSTRUCTURE FEATURES ------------------
# Per-motif microstructure: dwell mean/CV, exit entropy, entry rate
compute_per_motif_microfeatures <- function(seq_labels,
                                            frame.behavior,
                                            min_runs  = 5,
                                            min_exits = 10) {
  seq_labels <- as.integer(seq_labels)
  n          <- length(seq_labels)
  if (n == 0) return(list())
  
  motifs       <- sort(unique(seq_labels))
  duration_sec <- n * frame.behavior
  
  # Runs by RLE
  rl            <- rle(seq_labels)
  run_labels    <- rl$values
  run_lengths   <- rl$lengths
  run_dwell_sec <- run_lengths * frame.behavior
  
  # Entries per motif = #runs of that motif
  runs_per_motif <- table(factor(run_labels, levels = motifs))
  
  # Exit transitions (exclude self-loops at frame level)
  exits_from <- integer(0)
  exits_to   <- integer(0)
  if (n >= 2) {
    from <- seq_labels[-n]
    to   <- seq_labels[-1]
    keep <- from != to
    exits_from <- from[keep]
    exits_to   <- to[keep]
  }
  
  # Precompute exit counts per motif (from, to, n)
  exit_df <- if (length(exits_from)) {
    as.data.frame(
      table(
        factor(exits_from, levels = motifs),
        factor(exits_to,   levels = motifs)
      )
    )
  } else {
    as.data.frame(
      table(
        factor(integer(0), levels = motifs),
        factor(integer(0), levels = motifs)
      )
    )
  }
  names(exit_df) <- c("from", "to", "n")
  
  total_exits <- tapply(exit_df$n, exit_df$from, sum)
  if (is.null(total_exits)) {
    total_exits <- setNames(rep(0L, length(motifs)), motifs)
  }
  
  out <- list()
  
  for (m in motifs) {
    m_chr <- as.character(m)
    
    # ----- Dwell stats for motif m -----
    idx_runs_m <- which(run_labels == m)
    K          <- length(idx_runs_m)
    
    if (K >= min_runs) {
      dwell_sec  <- run_dwell_sec[idx_runs_m]
      dwell_mean <- mean(dwell_sec)
      dwell_cv   <- if (dwell_mean > 0) stats::sd(dwell_sec) / dwell_mean else NA_real_
    } else {
      dwell_mean <- NA_real_
      dwell_cv   <- NA_real_
    }
    
    out[[paste0("dwell_mean_sec_m", m_chr)]] <- as.numeric(dwell_mean)
    out[[paste0("dwell_cv_m",       m_chr)]] <- as.numeric(dwell_cv)
    
    # ----- Exit entropy for motif m -----
    tot_ex <- as.integer(total_exits[m_chr])
    if (is.na(tot_ex)) tot_ex <- 0L
    
    if (tot_ex >= min_exits) {
      row_m <- exit_df[exit_df$from == m_chr, , drop = FALSE]
      p     <- if (nrow(row_m)) row_m$n / sum(row_m$n) else numeric(0)
      p     <- p[p > 0]
      H     <- if (length(p)) -sum(p * log2(p)) else NA_real_
    } else {
      H <- NA_real_
    }
    
    out[[paste0("exit_entropy_m", m_chr)]] <- as.numeric(H)
    
    # ----- Entry rate per minute for motif m -----
    entries <- as.integer(runs_per_motif[m_chr])
    if (is.na(entries)) entries <- 0L
    
    rate_per_min <- if (duration_sec > 0) (entries / (duration_sec / 60)) else NA_real_
    out[[paste0("entries_per_min_m", m_chr)]] <- as.numeric(rate_per_min)
  }
  
  out
}

