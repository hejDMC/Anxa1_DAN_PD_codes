# ------------------ DISCOVER ALIGNED FILES -------------------
aligned_files <- list.files(
  wd,
  pattern    = "_aligned\\.csv$",
  full.names = TRUE,
  recursive  = TRUE
)

if (!length(aligned_files)) {
  stop("No *_aligned.csv files found in ", wd)
}

# ------------------ LOOP OVER FILES --------------------------
results_list <- purrr::map(aligned_files, function(fpath) {
  
  message("Processing: ", basename(fpath))
  
  df <- readr::read_csv(fpath, show_col_types = FALSE)
  
  if (!"motif" %in% names(df)) {
    warning("File ", basename(fpath), " has no 'motif' column. Skipping.")
    return(NULL)
  }
  
  seq_labels <- df$motif
  if (all(is.na(seq_labels)) || length(seq_labels) == 0) {
    warning("Empty/invalid motif sequence in ", basename(fpath))
    return(NULL)
  }
  
  # ----- Core features from motif sequence -----
  feats  <- compute_features_from_sequence(seq_labels)
  motifs <- feats$motifs
  
  # Usage feature names
  usage_count_names <- paste0("motif_", motifs, "_count")
  usage_prop_names  <- paste0("motif_", motifs, "_prop")
  usage_sec_names   <- paste0("motif_", motifs, "_sec")
  
  # ----- Transitions: COUNTS (n_mX_to_mY) -------------------
  trans_counts_df <- feats$trans_counts %>%
    mutate(
      from  = as.integer(as.character(from)),
      to    = as.integer(as.character(to)),
      col_n = paste0("n_m", from, "_to_m", to)
    )
  
  trans_vec_n <- setNames(as.list(trans_counts_df$n), trans_counts_df$col_n)
  
  # ----- Microstructure features -----------------------------
  micro_list <- compute_per_motif_microfeatures(
    seq_labels,
    frame.behavior,
    min_runs  = min_runs_per_motif,
    min_exits = min_exits_per_motif
  )
  
  # ----- Metadata from aligned file --------------------------
  meta_cols <- intersect(
    c("mouse.ID", "group", "experiment", "ctrl.vs.exp",
      "genotype", "sex", "treatment"),
    names(df)
  )
  
  meta_list <- list()
  if (length(meta_cols)) {
    meta_vals <- df[1, meta_cols, drop = FALSE] %>%
      mutate(across(everything(), ~ as.character(.x)))
    meta_list <- as.list(meta_vals)
  }
  
  # Video ID from file name (without _aligned.csv)
  video_id <- sub("_aligned\\.csv$", "", basename(fpath))
  
  # ----- Assemble row for this video -------------------------
  row_list <- c(
    list(video = video_id),
    meta_list,
    setNames(as.list(feats$counts),                  usage_count_names),
    setNames(as.list(feats$props),                   usage_prop_names),
    setNames(as.list(feats$counts * frame.behavior), usage_sec_names),
    trans_vec_n,
    micro_list
  )
  
  tibble::as_tibble_row(row_list)
})

results_list <- purrr::compact(results_list)
if (!length(results_list)) {
  stop("No videos processed. Check *_aligned.csv files.")
}

features_df <- dplyr::bind_rows(results_list)

# ============================================================
# DERIVE TRANSITION PROBABILITIES p_mX_to_mY FROM n_mX_to_mY
# ============================================================

n_cols <- grep("^n_m\\d+_to_m\\d+$", names(features_df), value = TRUE)

if (length(n_cols)) {
  message("Deriving p_mX_to_mY from n_mX_to_mY ...")
  
  # Long format: one row per video, from, to
  n_long <- features_df %>%
    select(video, all_of(n_cols)) %>%
    pivot_longer(
      cols      = all_of(n_cols),
      names_to  = "edge",
      values_to = "n"
    ) %>%
    mutate(
      from = as.integer(sub("^n_m(\\d+)_to_m(\\d+)$", "\\1", edge)),
      to   = as.integer(sub("^n_m(\\d+)_to_m(\\d+)$", "\\2", edge))
    )
  
  # Normalize per video + FROM motif
  n_long <- n_long %>%
    group_by(video, from) %>%
    mutate(
      total_n = sum(n, na.rm = TRUE),
      p       = ifelse(total_n > 0, n / total_n, 0)
    ) %>%
    ungroup()
  
  # Wide format for probabilities: p_mX_to_mY
  p_wide <- n_long %>%
    mutate(col_p = paste0("p_m", from, "_to_m", to)) %>%
    select(video, col_p, p) %>%
    distinct() %>%
    pivot_wider(
      names_from  = col_p,
      values_from = p,
      values_fill = 0
    )
  
  # Join p_mX_to_mY back onto features_df
  features_df <- features_df %>%
    left_join(p_wide, by = "video")
}

# ============================================================
# MOTIF FILTER (MIN_MICE_PER_MOTIF)
# ============================================================

if (!file.exists(mean_speed_path)) {
  stop("mean_speed_per_motif_overall.csv not found at: ", mean_speed_path)
}

mean_speed_df <- readr::read_csv(mean_speed_path, show_col_types = FALSE)

if (!"motif" %in% names(mean_speed_df)) {
  stop("mean_speed_per_motif_overall.csv must contain a 'motif' column.")
}
if (!motif_count_col %in% names(mean_speed_df)) {
  stop(
    "mean_speed_per_motif_overall.csv must contain a column '", motif_count_col,
    "' with per-motif mouse counts. Edit 'motif_count_col' in the script if needed."
  )
}

motifs_keep <- mean_speed_df %>%
  dplyr::filter(.data[[motif_count_col]] >= MIN_MICE_PER_MOTIF) %>%
  pull(motif) %>%
  unique() %>%
  as.integer() %>%
  sort()

message("Keeping ", length(motifs_keep),
        " motif(s) with n_mice >= ", MIN_MICE_PER_MOTIF, ".")

cols_to_drop <- character(0)

# --- motif_X_count / prop / sec ------------------------------
motif_count_cols <- grep("^motif_\\d+_count$", names(features_df), value = TRUE)
if (length(motif_count_cols)) {
  m_ids <- as.integer(sub("^motif_(\\d+)_count$", "\\1", motif_count_cols))
  cols_to_drop <- c(cols_to_drop, motif_count_cols[!(m_ids %in% motifs_keep)])
}

motif_prop_cols <- grep("^motif_\\d+_prop$", names(features_df), value = TRUE)
if (length(motif_prop_cols)) {
  m_ids <- as.integer(sub("^motif_(\\d+)_prop$", "\\1", motif_prop_cols))
  cols_to_drop <- c(cols_to_drop, motif_prop_cols[!(m_ids %in% motifs_keep)])
}

motif_sec_cols <- grep("^motif_\\d+_sec$", names(features_df), value = TRUE)
if (length(motif_sec_cols)) {
  m_ids <- as.integer(sub("^motif_(\\d+)_sec$", "\\1", motif_sec_cols))
  cols_to_drop <- c(cols_to_drop, motif_sec_cols[!(m_ids %in% motifs_keep)])
}

# --- transitions: drop any n_mX_to_mY / p_mX_to_mY with X or Y not in motifs_keep
trans_n_cols <- grep("^n_m\\d+_to_m\\d+$", names(features_df), value = TRUE)
if (length(trans_n_cols)) {
  from_ids <- as.integer(sub("^n_m(\\d+)_to_m(\\d+)$", "\\1", trans_n_cols))
  to_ids   <- as.integer(sub("^n_m(\\d+)_to_m(\\d+)$", "\\2", trans_n_cols))
  keep_idx <- from_ids %in% motifs_keep & to_ids %in% motifs_keep
  cols_to_drop <- c(cols_to_drop, trans_n_cols[!keep_idx])
}

trans_p_cols <- grep("^p_m\\d+_to_m\\d+$", names(features_df), value = TRUE)
if (length(trans_p_cols)) {
  from_ids <- as.integer(sub("^p_m(\\d+)_to_m(\\d+)$", "\\1", trans_p_cols))
  to_ids   <- as.integer(sub("^p_m(\\d+)_to_m(\\d+)$", "\\2", trans_p_cols))
  keep_idx <- from_ids %in% motifs_keep & to_ids %in% motifs_keep
  cols_to_drop <- c(cols_to_drop, trans_p_cols[!keep_idx])
}

# --- microfeatures: dwell_mean_sec_mX, dwell_cv_mX, exit_entropy_mX, entries_per_min_mX
dwell_mean_cols <- grep("^dwell_mean_sec_m\\d+$", names(features_df), value = TRUE)
if (length(dwell_mean_cols)) {
  m_ids <- as.integer(sub("^dwell_mean_sec_m(\\d+)$", "\\1", dwell_mean_cols))
  cols_to_drop <- c(cols_to_drop, dwell_mean_cols[!(m_ids %in% motifs_keep)])
}

dwell_cv_cols <- grep("^dwell_cv_m\\d+$", names(features_df), value = TRUE)
if (length(dwell_cv_cols)) {
  m_ids <- as.integer(sub("^dwell_cv_m(\\d+)$", "\\1", dwell_cv_cols))
  cols_to_drop <- c(cols_to_drop, dwell_cv_cols[!(m_ids %in% motifs_keep)])
}

exit_entropy_cols <- grep("^exit_entropy_m\\d+$", names(features_df), value = TRUE)
if (length(exit_entropy_cols)) {
  m_ids <- as.integer(sub("^exit_entropy_m(\\d+)$", "\\1", exit_entropy_cols))
  cols_to_drop <- c(cols_to_drop, exit_entropy_cols[!(m_ids %in% motifs_keep)])
}

entries_per_min_cols <- grep("^entries_per_min_m\\d+$", names(features_df), value = TRUE)
if (length(entries_per_min_cols)) {
  m_ids <- as.integer(sub("^entries_per_min_m(\\d+)$", "\\1", entries_per_min_cols))
  cols_to_drop <- c(cols_to_drop, entries_per_min_cols[!(m_ids %in% motifs_keep)])
}

cols_to_drop <- unique(cols_to_drop)

if (length(cols_to_drop)) {
  final_df <- features_df[, setdiff(names(features_df), cols_to_drop), drop = FALSE]
  message("Dropped ", length(cols_to_drop),
          " motif-related column(s) below MIN_MICE_PER_MOTIF.")
} else {
  final_df <- features_df
}

# ============================================================
# CLEAN NUMERIC FEATURES: NA → 0
# ============================================================

numeric_feature_cols <- c(
  grep("^motif_\\d+_count$",        names(final_df), value = TRUE),
  grep("^motif_\\d+_prop$",         names(final_df), value = TRUE),
  grep("^motif_\\d+_sec$",          names(final_df), value = TRUE),
  grep("^n_m\\d+_to_m\\d+$",        names(final_df), value = TRUE),
  grep("^p_m\\d+_to_m\\d+$",        names(final_df), value = TRUE),
  grep("^dwell_mean_sec_m\\d+$",    names(final_df), value = TRUE),
  grep("^dwell_cv_m\\d+$",          names(final_df), value = TRUE),
  grep("^exit_entropy_m\\d+$",      names(final_df), value = TRUE),
  grep("^entries_per_min_m\\d+$",   names(final_df), value = TRUE)
)

numeric_feature_cols <- unique(numeric_feature_cols)

if (length(numeric_feature_cols)) {
  final_df[numeric_feature_cols] <- lapply(final_df[numeric_feature_cols], function(x) {
    x[is.na(x)] <- 0
    x
  })
}

# ============================================================
# ORDER METADATA COLUMNS & SAVE
# ============================================================
for (nm in c("mouse.ID", "group", "experiment", "ctrl.vs.exp")) {
  if (!nm %in% names(final_df)) {
    final_df[[nm]] <- final_df[[nm]]
  }
}

final_df <- final_df %>%
  relocate(any_of(c("video", "mouse.ID", "group", "experiment", "ctrl.vs.exp")))

out_csv <- file.path(wd, "vame_sequence_features.csv")
readr::write_csv(final_df, out_csv)
message("Saved: ", out_csv)
