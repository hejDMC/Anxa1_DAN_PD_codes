# ============================================================
# VAME behavioral feature extraction for XGBoost classification
# Author: Alessandro Contestabile
#
# Description:
#   - Extracts behavioral features from frame-wise VAME motif sequences for individual OFT recordings.
#   - Quantifies motif usage (counts, proportions, duration).
#   - Calculates motif-to-motif transition counts and conditional transition probabilities.
#   - Extracts motif microstructure features, including dwell time, dwell-time variability, transition entropy, and motif entry frequency.
#   - Retains motifs represented in a predefined minimum number of mice.
#   - Generates a per-video feature matrix for subsequent machine-learning analyses.
#
# Requirements:
#   - Frame-wise *_aligned.csv files generated during OFT preprocessing.
#   - mean_speed_per_motif_overall.csv generated by the Figure 5 analysis script.
#
# Outputs:
#   - vame_sequence_features.csv:
#     One row per recording, with experimental metadata
#     and VAME-derived behavioral features.
#
# Notes:
#   - Motif transitions are calculated between consecutive motif episodes, excluding self-transitions.
#   - Motifs are retained when represented in at least 40 mice (MIN_MICE_PER_MOTIF).
#   - Missing numerical features are replaced with zero in the final feature matrix.
# ============================================================

