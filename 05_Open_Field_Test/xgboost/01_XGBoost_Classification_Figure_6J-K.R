# ------------------ TRAINING DATA: TETANUS ONLY ------------------
train_df <- final_df %>% dplyr::filter(experiment == "oft_Tetx")
if (nrow(train_df) == 0) {
  stop("No rows with experiment == 'oft_Tetx' found.")
}

