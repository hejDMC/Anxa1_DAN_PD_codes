# ------------------ PLOTTING HELPERS ------------------
plot_cm_with_p <- function(cm_obj, title, low_col = "white", high_col = "#ffb437") {
  m <- as.data.frame(cm_obj$table)
  names(m) <- c("Prediction", "Reference", "Freq")
  m <- m %>%
    dplyr::group_by(Reference) %>%
    dplyr::mutate(Prop = Freq / sum(Freq)) %>%
    dplyr::ungroup()
  
  pval <- as.numeric(cm_obj$overall["AccuracyPValue"])
  ptxt <- ifelse(
    is.na(pval),
    "p = NA",
    paste0("p = ", formatC(pval, format = "g", digits = 3))
  )
  
  ggplot(m, aes(x = Reference, y = Prediction, fill = Prop)) +
    geom_tile(color = "white") +
    geom_text(
      aes(label = paste0(Freq, "\n(", scales::percent(Prop, accuracy = 0.1), ")")),
      size = 4
    ) +
    scale_fill_gradient(
      name   = "Proportion",
      low    = low_col,
      high   = high_col,
      limits = c(0, 1)
    ) +
    labs(
      title = paste0(title, " — ", ptxt),
      x = "True label",
      y = "Predicted label"
    ) +
    theme_classic(base_size = 12) +
    theme(legend.position = "none")
}

plot_score_density <- function(df, title) {
  stopifnot(all(c("pred_prob", "ctrl.vs.exp") %in% names(df)))
  
  df <- df %>%
    dplyr::mutate(
      y = dplyr::case_when(
        grepl("ctrl", tolower(ctrl.vs.exp)) ~ "Control",
        grepl("exp|6ohda|pd|lesion|mitopark|mfn2", tolower(ctrl.vs.exp)) ~ "Experimental",
        TRUE ~ NA_character_
      )
    ) %>%
    dplyr::filter(!is.na(y), is.finite(pred_prob))
  
  ggplot(df, aes(x = pred_prob, fill = y)) +
    geom_density(alpha = 0.35) +
    scale_fill_manual(values = c(Control = "lightgrey", Experimental = "black")) +
    labs(
      title = paste0(title, " — score density"),
      x = "Predicted probability (Experimental)",
      y = "Density",
      fill = NULL
    ) +
    theme_classic(base_size = 12) +
    theme(
      legend.position      = c(0.8, 0.9),
      legend.justification = c(1, 1),
      legend.background    = element_rect(fill = "white", color = NA),
      legend.key           = element_rect(fill = NA, color = NA)
    ) +
    guides(fill = guide_legend(override.aes = list(alpha = 1)))
}

