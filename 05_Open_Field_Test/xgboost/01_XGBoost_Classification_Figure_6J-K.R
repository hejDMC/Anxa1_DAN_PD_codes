# ------------------ LABEL HELPERS ------------------
map_label01 <- function(x) {
  if (is.numeric(x)) return(as.integer(x > 0))
  x_low <- tolower(as.character(x))
  y <- ifelse(grepl("ctrl", x_low), 0L,
              ifelse(grepl("exp|6ohda|pd|lesion|mitopark|mfn2", x_low), 1L, NA_integer_))
  # If still NA, but exactly 2 classes, map second level → 1
  if (any(is.na(y)) && length(unique(na.omit(x_low))) == 2) {
    levs <- sort(unique(na.omit(x_low)))
    y <- as.integer(x_low == levs[2])
  }
  y
}
is_ctrl <- function(x) grepl("ctrl", tolower(as.character(x)))

# ------------------ STANDARDIZATION (FIT ON TETANUS CONTROLS) ------------------
fit_scaler <- function(df_ref, cols) {
  X <- as.data.frame(df_ref[, cols, drop = FALSE])
  mu <- vapply(X, function(z) mean(as.numeric(z), na.rm = TRUE), numeric(1))
  sd <- vapply(X, function(z) stats::sd(as.numeric(z), na.rm = TRUE), numeric(1))
  sd[!is.finite(sd) | sd == 0] <- 1
  list(mu = mu, sd = sd)
}

apply_scaler <- function(df, cols, sc) {
  X <- as.data.frame(df[, cols, drop = FALSE])
  for (nm in cols) {
    X[[nm]] <- (as.numeric(X[[nm]]) - sc$mu[[nm]]) / sc$sd[[nm]]
  }
  X
}

