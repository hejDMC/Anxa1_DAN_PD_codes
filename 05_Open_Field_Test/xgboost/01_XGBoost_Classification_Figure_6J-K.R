# ------------------ PER-COHORT EVALUATION (ROC-OPTIMAL THRESHOLD) ------------------
optimal_threshold <- function(y_true01, probs) {
  roc_obj <- pROC::roc(response = y_true01, predictor = probs, quiet = TRUE)
  coords <- pROC::coords(
    roc_obj, "best", best.method = "youden",
    ret = c("threshold", "sensitivity", "specificity", "accuracy"),
    transpose = FALSE
  )
  get1 <- function(x) as.numeric(x)[1]
  list(
    threshold = get1(coords$threshold),
    sens      = get1(coords$sensitivity),
    spec      = get1(coords$specificity),
    acc       = get1(coords$accuracy),
    roc       = roc_obj
  )
}

evaluate_on_experiment <- function(exp_name) {
  df <- final_df %>% dplyr::filter(experiment == exp_name)
  if (nrow(df) == 0) return(NULL)
  
  X <- as.matrix(df[, feature_cols, drop = FALSE])
  storage.mode(X) <- "double"
  probs <- predict(xgb_fit, xgb.DMatrix(X))
  
  out <- list(
    pred_df = tibble::tibble(
      video       = df$video,
      experiment  = df$experiment,
      ctrl.vs.exp = df$ctrl.vs.exp,
      pred_prob   = probs
    )
  )
  
  if ("ctrl.vs.exp" %in% names(df)) {
    y <- map_label01(df$ctrl.vs.exp)
    ok <- !is.na(y)
    if (any(ok) && length(unique(y[ok])) == 2) {
      opt <- optimal_threshold(y[ok], probs[ok])
      thr <- opt$threshold
      preds <- ifelse(probs >= thr, 1L, 0L)
      cm <- caret::confusionMatrix(
        factor(preds[ok], levels = c(0, 1), labels = c("Control", "Experimental")),
        factor(y[ok],     levels = c(0, 1), labels = c("Control", "Experimental"))
      )
      out$cm    <- cm
      out$thr   <- thr
      out$auc   <- as.numeric(pROC::auc(opt$roc))
      out$acc_p <- as.numeric(cm$overall["AccuracyPValue"])
    }
  }
  out
}

