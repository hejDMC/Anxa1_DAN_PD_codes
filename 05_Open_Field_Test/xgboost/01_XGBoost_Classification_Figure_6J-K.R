mk_panels <- function(res, name, pal_low = "white", pal_high = "#ffb437") {
  if (is.null(res)) {
    return(list(
      cm  = ggplot() + theme_void() + ggtitle(paste(name, "— no data")),
      den = ggplot() + theme_void()
    ))
  }
  
  p_den <- plot_score_density(res$pred_df, name)
  
  if (!is.null(res$cm)) {
    p_cm <- plot_cm_with_p(
      res$cm,
      paste0(name, " (opt thr=", round(res$thr, 3), ")"),
      low_col  = pal_low,
      high_col = pal_high
    )
  } else {
    p_cm <- ggplot() + theme_void() +
      ggtitle(paste(name, "— no labels or single class"))
  }
  
  list(cm = p_cm, den = p_den)
}

