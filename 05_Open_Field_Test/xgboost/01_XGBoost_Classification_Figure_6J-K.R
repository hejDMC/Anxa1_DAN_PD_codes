  stop("Some tetanus rows have unmappable ctrl.vs.exp labels.")
}

X_train <- as.matrix(train_df[, feature_cols, drop = FALSE])
storage.mode(X_train) <- "double"
dtrain <- xgb.DMatrix(data = X_train, label = y_train)

# ------------------ XGBOOST MODEL + CV ------------------
params <- list(
  objective = "binary:logistic",
  eval_metric = c("logloss", "auc"),
  max_depth = 4,
  eta = 0.05,
  subsample = 0.8,
  colsample_bytree = 0.8,
  min_child_weight = 1,
  lambda = 1
)

cv_nround <- 800
cv_nfold  <- 5

cv <- xgb.cv(
  params = params,
  data   = dtrain,
  nrounds = cv_nround,
  nfold   = cv_nfold,
  stratified = TRUE,
  showsd = TRUE,
  verbose = 0,
  early_stopping_rounds = 50,
  maximize = FALSE
)

best_nrounds <- cv$best_iteration
cat("Best nrounds:", best_nrounds,
    " | CV AUC:", cv$evaluation_log$test_auc_mean[best_nrounds], "\n")

xgb_fit <- xgb.train(
  params = params,
  data   = dtrain,
  nrounds = best_nrounds,
  verbose = 0
)

# ------------------ TETANUS: FOLD-WISE CV PREDICTIONS ------------------
folds <- createFolds(y_train, k = cv_nfold, list = TRUE, returnTrain = FALSE)
pred_all <- rep(NA_real_, length(y_train))

for (i in seq_along(folds)) {
  idx_val  <- folds[[i]]
  dtrain_i <- xgb.DMatrix(data = X_train[-idx_val, , drop = FALSE],
                          label = y_train[-idx_val])
  dval_i   <- xgb.DMatrix(data = X_train[idx_val,  , drop = FALSE],
                          label = y_train[idx_val])
  fit_i <- xgb.train(
    params  = params,
    data    = dtrain_i,
    nrounds = best_nrounds,
    verbose = 0
  )
  pred_all[idx_val] <- predict(fit_i, dval_i)
}

